def _create_old_generation_schema(schema: str, *, duplicate: bool = False) -> None:
    with psycopg.connect(DSN, autocommit=True) as conn:
        conn.execute(f'CREATE SCHEMA "{schema}"')
        conn.execute(f'SET search_path TO "{schema}", public')
        conn.execute(
            """
            CREATE TABLE embedding_profile (
                profile_id TEXT PRIMARY KEY,
                provider TEXT NOT NULL,
                model TEXT NOT NULL,
                dimension INTEGER NOT NULL,
                config_fingerprint TEXT NOT NULL UNIQUE,
                created_at TIMESTAMPTZ NOT NULL DEFAULT now()
            )
            """
        )
        conn.execute(
            """
            CREATE TABLE space_generation (
                generation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                space_key TEXT NOT NULL,
                profile_id TEXT NOT NULL REFERENCES embedding_profile(profile_id),
                state TEXT NOT NULL CHECK (state IN ('building','active','retired')),
                created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                activated_at TIMESTAMPTZ,
                UNIQUE (space_key, generation_id),
                CHECK (
                    (state='building' AND activated_at IS NULL)
                    OR (state IN ('active','retired') AND activated_at IS NOT NULL)
                )
            )
            """
        )
        profile = HashedEmbedder().profile
        conn.execute(
            """
            INSERT INTO embedding_profile
                (profile_id, provider, model, dimension, config_fingerprint)
            VALUES (%s, %s, %s, %s, %s)
            """,
            (
                profile.config_fingerprint,
                profile.provider,
                profile.model,
                profile.dimension,
                profile.config_fingerprint,
            ),
        )
        if duplicate:
            conn.execute(
                """
                INSERT INTO space_generation (space_key, profile_id, state)
                VALUES ('DUP', %s, 'building'), ('DUP', %s, 'building')
                """,
                (profile.config_fingerprint, profile.config_fingerprint),
            )


def _write_queries(
    path: Path,
    *,
    space_key: str,
    source_id: str,
    expected_heading: str = "Release",
) -> Path:
    path.write_text(
        f"""space_key: {space_key}
queries:
  - id: source
    question: release rollback guide
    category: source_coverage
    expected_source_id: {source_id}
  - id: heading
    question: release rollback
    category: heading_intent
    expected_source_id: {source_id}
    expected_heading: {expected_heading}
  - id: paraphrase
    question: how to rollback a release
    category: en_paraphrase
    expected_source_id: {source_id}
  - id: keyword
    question: release rollback
    category: en_keyword
    expected_source_id: {source_id}
  - id: korean
    question: 릴리스 롤백 release rollback
    category: ko_morphology
    expected_source_id: {source_id}
""",
        encoding="utf-8",
    )
    return path


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _prepare_building(store: PgVectorStore, *, space_key: str, source_id: str = "source") -> int:
    embedder = HashedEmbedder()
    building = store.create_building_generation(space_key=space_key)
    document = SourceDocument(
        source_id=source_id,
        title="Release guide",
        space_key=space_key,
        body="## Release\nrelease rollback guide procedure",
    )
    chunks = chunk_document(document)
    store.replace_source(
        space_key=space_key,
        source_id=source_id,
        chunks=chunks,
        embeddings=embedder.embed([chunk.embedding_text for chunk in chunks]),
        generation_id=building.generation_id,
    )
    return building.generation_id


def _complete_manifest(
    store: PgVectorStore, *, space_key: str, generation_id: int, source_id: str = "source"
) -> int:
    revision = store.begin_manifest(space_key=space_key, generation_id=generation_id)
    store.finalize_manifest(
        space_key=space_key,
        generation_id=generation_id,
        source_counts={source_id: 1},
        total_chunks=1,
        page_count=1,
        skipped_pages=0,
        suppressed_pages=0,
    )
    return revision


def _prepare_legacy_cleanup(store: PgVectorStore, *, space_key: str, tmp_path: Path) -> int:
    embedder = HashedEmbedder()
    legacy_document = SourceDocument(
        source_id="legacy",
        title="Legacy",
        space_key=space_key,
        body="## Legacy\nold content",
    )
    legacy_chunks = chunk_document(legacy_document)
    store.replace_source(
        space_key=space_key,
        source_id="legacy",
        chunks=legacy_chunks,
        embeddings=embedder.embed([chunk.embedding_text for chunk in legacy_chunks]),
    )
    with psycopg.connect(DSN) as conn:
        conn.execute(
            "UPDATE chunks SET generation_id=NULL WHERE space_key=%s AND source_id='legacy'",
            (space_key,),
        )
    generation_id = _prepare_building(store, space_key=space_key)
    _complete_manifest(store, space_key=space_key, generation_id=generation_id)
    queries = _write_queries(
        tmp_path / f"{space_key}.yaml", space_key=space_key, source_id="source"
    )
    validate_generation(
        store,
        embedder,
        space_key=space_key,
        generation_id=generation_id,
        queries_path=queries,
        expected_queries_sha256=_sha256(queries),
    )
    store.activate_generation(space_key=space_key, generation_id=generation_id)
    return generation_id


class _TwoPageBatchClient:
    def __init__(self) -> None:
        body = Body(
            atlas_doc_format=BodyFormat(
                value=(
                    '{"type":"doc","version":1,"content":['
                    '{"type":"paragraph","content":[{"type":"text","text":"body"}]}'
                    "]}"
                )
            )
        )
        self.pages = {
            page_id: Page(
                id=page_id,
                title=page_id,
                type="page",
                spaceId="space-1",
                parentId="folder-1",
                parentType="folder",
                body=body,
            )
            for page_id in ("page-1", "page-2")
        }

    async def get_space_by_key(self, space_key: str) -> Space:
        return Space(id="space-1", key=space_key)

    async def get_folder(self, folder_id: str) -> dict[str, object]:
        return {"id": folder_id, "spaceId": "space-1", "title": "Folder"}

    async def iter_folder_descendants(
        self, folder_id: str, *, batch_size: int = 50, depth: int = 10
    ) -> AsyncIterator[Page]:
        del folder_id, batch_size, depth
        for page in self.pages.values():
            yield page

    async def get_page(self, page_id: str, *, body_format: str = "atlas_doc_format") -> Page:
        del body_format
        return self.pages[page_id]


class _RetireAfterFirstWriteStore(PgVectorStore):
    def __init__(self, *, target_generation_id: int) -> None:
        super().__init__(
            DSN,
            profile=HashedEmbedder().profile,
            mode=ProfileMode.OBSERVE,
        )
        self._target_generation_id = target_generation_id
        self._write_count = 0

    def replace_source(
        self,
        *,
        space_key: str,
        source_id: str,
        chunks: list[Chunk],
        embeddings: list[list[float]],
        generation_id: int | None = None,
    ) -> int:
        result = super().replace_source(
            space_key=space_key,
            source_id=source_id,
            chunks=chunks,
            embeddings=embeddings,
            generation_id=generation_id,
        )
        self._write_count += 1
        if self._write_count == 1:
            with psycopg.connect(DSN) as conn:
                conn.execute(
                    "UPDATE space_generation SET state='retired' "
                    "WHERE space_key=%s AND generation_id=%s",
                    (space_key, self._target_generation_id),
                )
        return result


